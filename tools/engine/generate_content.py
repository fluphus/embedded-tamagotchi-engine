#!/usr/bin/env python3
"""Generate presentation definitions and stable-ID food tables from a content manifest."""
import argparse, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[2]
def generate(name,check=False):
    directory=ROOT/'src/content'/name
    manifest=json.loads((directory/'manifest.json').read_text())
    for field in ('forms','foods','special_foods'):
        ids=[item['id'] for item in manifest[field]]
        if len(ids)!=len(set(ids)) or any(not 0<=id<255 for id in ids):raise ValueError('duplicate/out-of-range stable IDs')
    if not 1<=len(manifest['forms'])<=32 or not 4<=len(manifest['foods'])<=32 or not 1<=len(manifest['special_foods'])<=32:raise ValueError('capacity exceeded')
    quote=lambda value:json.dumps(value,ensure_ascii=True)
    definition='// Generated by tools/engine/generate_content.py; edit manifest.json.\n'
    definition+=f'inline constexpr uint32_t PackageId={manifest["package_id"]}u;\ninline constexpr const char* Title={quote(manifest["title"])};\ninline constexpr FormDefinition Forms[]={{\n'
    definition+=''.join(f'    {{{item["id"]},{quote(item["name"])},{item["asset"]}}},\n' for item in manifest['forms'])+'};\n'
    definition+=f'inline constexpr bool LegacyUI={str(manifest["legacy_ui"]).lower()};\ninline constexpr bool LegacyIdleMapping={str(manifest["legacy_idle_mapping"]).lower()};\n'
    definition+='inline constexpr const char* TierNames[]={'+','.join(quote(v) for v in manifest['tier_names'])+'};\n'
    definition+='inline constexpr const char* StageNames[]={'+','.join(quote(v) for v in manifest['stage_names'])+'};\n'
    config='// Generated from manifest.json.\n#pragma once\n'+''.join('#define '+key+' '+str(value)+'\n' for key,value in manifest['config'].items())
    table='// Generated by tools/engine/generate_content.py; edit manifest.json.\n#pragma once\n#include <stdint.h>\n'
    table+='struct FoodItem {uint8_t id;const char* name;bool is_healthy;int8_t health_delta;};\nenum FoodId : uint8_t {\n'
    table+=''.join(f'    FOOD_{item["key"].upper()}={item["id"]},\n' for item in manifest['foods'])+f'    FOOD_COUNT={len(manifest["foods"])}\n}};\n'
    table+='inline const FoodItem FOOD_TABLE[FOOD_COUNT]={\n'+''.join(f'    {{{item["id"]},{quote(item["name"])},{str(item["healthy"]).lower()},{item["health_delta"]}}},\n' for item in manifest['foods'])+'};\n'
    table+='struct SpecialFoodItem {uint8_t id;const char* name;const char* description;};\nenum SpecialFoodId : uint8_t {\n'+''.join(f'    SFOOD_{item["key"].upper()}={item["id"]},\n' for item in manifest['special_foods'])+f'    SFOOD_COUNT={len(manifest["special_foods"])}\n}};\n'
    table+='inline const SpecialFoodItem SPECIAL_FOOD_TABLE[SFOOD_COUNT]={\n'+''.join(f'    {{{item["id"]},{quote(item["name"])},{quote(item["description"])}}},\n' for item in manifest['special_foods'])+'};\n'
    table+='struct CurseFoodItem {const char* name;const char* description;};\ninline const CurseFoodItem MAPO_TOFU={'+quote(manifest['curse_food']['name'])+','+quote(manifest['curse_food']['description'])+'};\n'
    for filename,text in [('definition.inc',definition),('food_table.h',table),('config.h',config)]:
        target=directory/filename
        if check:
            if target.read_text()!=text:raise SystemExit('stale generated file: '+str(target))
        else:target.write_text(text)
    print('PASS content definitions:',name)
if __name__=='__main__':
    parser=argparse.ArgumentParser();parser.add_argument('--content');parser.add_argument('--check',action='store_true');args=parser.parse_args()
    names=[args.content] if args.content else [p.parent.name for p in sorted((ROOT/'src/content').glob('*/manifest.json'))]
    for name in names:generate(name,args.check)
